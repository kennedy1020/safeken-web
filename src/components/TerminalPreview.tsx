export default function TerminalPreview() {
  const [activeTab, setActiveTab] = useState<TerminalTab>(TERMINAL_SCENARIOS[0]);
  const [copied, setCopied] = useState(false);

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(activeTab.command);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // Fallback
    }
  };

  return (
    <section id="terminal" className="py-20 border-t border-[var(--ks-rule)] bg-[var(--ks-paper)]">
      <div className="mx-auto max-w-6xl px-4 sm:px-6 lg:px-8">
        {/* Section Header */}
        <div className="max-w-3xl mb-8">
          <p className="text-xs font-semibold uppercase tracking-wider text-[var(--ks-patina)] mb-2">
            Deterministic Terminal Output
          </p>
          <h2 className="text-2xl sm:text-3xl font-semibold tracking-tight text-[var(--ks-ink)]">
            Exact Terminal Output in Under Two Seconds
          </h2>
          <p className="mt-2 text-sm sm:text-base text-[var(--ks-text-muted)]">
            Inspect real AST and manifest outputs for the top four vulnerability patterns.
          </p>
        </div>

        {/* Scenario Switcher Tabs */}
        <div className="flex flex-wrap items-center gap-2 mb-4">
          {TERMINAL_SCENARIOS.map((scenario) => {
            const isActive = activeTab.id === scenario.id;
            return (
              <button
                key={scenario.id}
                onClick={() => setActiveTab(scenario)}
                className={`px-3.5 py-1.5 rounded text-xs font-medium border transition-colors ${
                  isActive
                    ? 'border-[var(--ks-patina)] bg-[var(--ks-paper-raised)] text-[var(--ks-ink)] font-semibold'
                    : 'border-[var(--ks-rule)] bg-[var(--ks-paper-deep)] text-[var(--ks-text-muted)] hover:text-[var(--ks-ink)] hover:border-[var(--ks-edge)]'
                }`}
              >
                <span className="flex items-center gap-2">
                  <span
                    className={`w-1.5 h-1.5 rounded-full ${
                      scenario.exitCode === 0 ? 'bg-[var(--ks-patina)]' : 'bg-[var(--ks-vermilion)]'
                    }`}
                  />
                  <span>{scenario.label}</span>
                </span>
              </button>
            );
          })}
        </div>

        {/* Terminal Chrome Window */}
        <div className="rounded-lg border border-[var(--ks-edge)] bg-[var(--ks-paper-deep)] overflow-hidden">
          {/* Header Bar */}
          <div className="flex flex-wrap items-center justify-between gap-3 px-4 py-2.5 border-b border-[var(--ks-rule)] bg-[var(--ks-paper-raised)]">
            <div className="flex items-center gap-3 text-xs text-[var(--ks-text-muted)]">
              <span className="flex items-center gap-1.5 font-mono text-[11px] text-[var(--ks-ink)]">
                <Icon name="terminal" size={13} className="text-[var(--ks-patina)]" />
                <span>vibe-shield scan</span>
              </span>
              <span className="text-[var(--ks-rule)]">|</span>
              <span className="tabular-nums font-mono text-[11px]">
                {activeTab.duration}
              </span>
              <span className="text-[var(--ks-rule)]">|</span>
              <span
                className={`px-1.5 py-0.5 rounded text-[10px] font-mono font-semibold ${
                  activeTab.exitCode === 0
                    ? 'bg-[var(--ks-patina-pale)] text-[var(--ks-patina)]'
                    : 'bg-[var(--ks-vermilion)]/15 text-[var(--ks-vermilion)]'
                }`}
              >
                exit {activeTab.exitCode}
              </span>
            </div>

            <div className="flex items-center gap-3">
              <span className="hidden md:inline text-xs text-[var(--ks-text-muted)]">
                {activeTab.description}
              </span>
              <button
                onClick={handleCopy}
                className="flex items-center gap-1.5 px-2.5 py-1 rounded text-xs border border-[var(--ks-edge)] bg-[var(--ks-paper)] text-[var(--ks-text)] hover:border-[var(--ks-patina)] hover:text-[var(--ks-ink)] transition-colors"
                title="Copy terminal command"
              >
                <Icon name={copied ? 'check' : 'copy'} size={13} className={copied ? 'text-[var(--ks-patina)]' : ''} />
                <span>{copied ? 'Copied' : 'Copy Command'}</span>
              </button>
            </div>
          </div>

          {/* Terminal Command Line */}
          <div className="px-4 py-2 bg-[var(--ks-paper)]/40 border-b border-[var(--ks-rule)] font-mono text-xs flex items-center gap-2 text-[var(--ks-text)]">
            <span className="text-[var(--ks-patina)] font-bold select-none">$</span>
            <span className="text-[var(--ks-ink)]">{activeTab.command}</span>
          </div>

          {/* Terminal Logs Output */}
          <div className="p-4 sm:p-5 font-mono text-xs leading-relaxed space-y-1.5 overflow-x-auto text-[var(--ks-text)]">
            {activeTab.output.map((line, idx) => {
              if (line.type === 'divider') {
                return (
                  <div key={idx} className="text-[var(--ks-rule)] select-none py-1">
                    {line.content}
                  </div>
                );
              }
              if (line.type === 'danger') {
                return (
                  <div key={idx} className="text-[var(--ks-vermilion)] font-medium">
                    {line.content}
                  </div>
                );
              }
              if (line.type === 'warning') {
                return (
                  <div key={idx} className="text-amber-300">
                    {line.content}
                  </div>
                );
              }
              if (line.type === 'success') {
                return (
                  <div key={idx} className="text-[var(--ks-patina)] font-medium">
                    {line.content}
                  </div>
                );
              }
              if (line.type === 'dim') {
                return (
                  <div key={idx} className="text-[var(--ks-text-faint)]">
                    {line.content}
                  </div>
                );
              }
              if (line.type === 'info') {
                return (
                  <div key={idx} className="text-[var(--ks-ink)] font-semibold">
                    {line.content}
                  </div>
                );
              }
              return (
                <div key={idx} className="text-[var(--ks-text)]">
                  {line.content}
                </div>
              );
            })}
          </div>
        </div>
      </div>
    </section>
  );
}
