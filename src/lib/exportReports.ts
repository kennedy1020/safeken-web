// Client-side helper to download string content as a file
export function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}

export interface FindingItem {
  name?: string;
  issue?: string;
  ruleId?: string;
  severity?: 'CRITICAL' | 'HIGH' | 'WARN' | string;
  title?: string;
  description?: string;
  suggestedFix?: string;
}

// 1. Generate Markdown Report
export function exportToMarkdown(data: {
  type: 'manifest' | 'code';
  ecosystem?: string;
  scannedCount?: number;
  findings: FindingItem[];
}): string {
  const timestamp = new Date().toISOString();
  let md = `# SafeKen VibeShield Security Audit Report\n\n`;
  md += `- **Date:** ${timestamp}\n`;
  md += `- **Scanner:** @kennedy1020/vibe-shield v1.1.2\n`;
  md += `- **Audit Type:** ${data.type === 'manifest' ? `Dependency Slopsquatting (${data.ecosystem?.toUpperCase()})` : 'AST Code Vulnerability Audit'}\n`;
  md += `- **Total Findings:** ${data.findings.length}\n\n`;
  md += `---\n\n`;

  if (data.findings.length === 0) {
    md += `## ✅ Status: Clean\n\nNo vulnerabilities or hallucinated dependencies detected.\n`;
    return md;
  }

  if (data.type === 'manifest') {
    md += `## ⚠️ Flagged Hallucinated Dependencies (HTTP 404)\n\n`;
    md += `The following dependencies were not found on the public ${data.ecosystem?.toUpperCase()} registry and may expose the application to slopsquatting attacks:\n\n`;
    md += `| Package Name | Issue Description |\n`;
    md += `| :--- | :--- |\n`;
    for (const item of data.findings) {
      md += `| \`${item.name}\` | ${item.issue} |\n`;
    }
  } else {
    md += `## 🚨 Flagged Code Vulnerabilities\n\n`;
    data.findings.forEach((f, idx) => {
      md += `### ${idx + 1}. ${f.title} [${f.severity}]\n\n`;
      md += `- **Rule ID:** \`${f.ruleId}\`\n`;
      md += `- **Description:** ${f.description}\n\n`;
      md += `#### Suggested Remediation:\n\`\`\`typescript\n${f.suggestedFix}\n\`\`\`\n\n`;
    });
  }

  md += `\n---\n*Generated by [SafeKen VibeShield](https://github.com/kennedy1020/vibe-shield)*\n`;
  return md;
}

// 2. Generate SARIF v2.1.0 Report (OASIS standard for GitHub Security tab)
export function exportToSarif(data: {
  type: 'manifest' | 'code';
  ecosystem?: string;
  findings: FindingItem[];
}): string {
  const sarif = {
    $schema: 'https://raw.githubusercontent.com/oasis-tcs/sarif-spec/master/Schemata/sarif-schema-2.1.0.json',
    version: '2.1.0',
    runs: [
      {
        tool: {
          driver: {
            name: 'SafeKen VibeShield',
            version: '1.1.2',
            informationUri: 'https://github.com/kennedy1020/vibe-shield',
            rules: data.findings.map((f) => ({
              id: f.ruleId || 'slopsquatting-missing-package',
              shortDescription: {
                text: f.title || `Hallucinated ${data.ecosystem?.toUpperCase()} package: ${f.name}`,
              },
              fullDescription: {
                text: f.description || f.issue,
              },
              defaultConfiguration: {
                level: f.severity === 'WARN' ? 'warning' : 'error',
              },
            })),
          },
        },
        results: data.findings.map((f) => ({
          ruleId: f.ruleId || 'slopsquatting-missing-package',
          level: f.severity === 'WARN' ? 'warning' : 'error',
          message: {
            text: f.description || `${f.name}: ${f.issue}`,
          },
          locations: [
            {
              physicalLocation: {
                artifactLocation: {
                  uri: data.type === 'manifest' ? (data.ecosystem === 'npm' ? 'package.json' : 'requirements.txt') : 'snippet.tsx',
                },
              },
            },
          ],
        })),
      },
    ],
  };

  return JSON.stringify(sarif, null, 2);
}
